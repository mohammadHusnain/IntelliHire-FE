"""The candidate's own mock interviews: the list, the detail and the feedback state (FR-14, UC-03). Nobody else's, ever."""
from django.conf import settings
from django.db.models import Count, Q

from apps.Module7_Interviews.models import FINISHED_STATUSES, OPEN_STATUSES, InterviewSession, SessionStatus
from apps.Module7_Interviews.services import engine

DISCLAIMER = "Generated by AI for your own practice."
MESSAGES = {
    "none": "Feedback is not available yet.",
    "generating": "Your feedback is being prepared.",
    "ready": "",
    "partial": "This session ended early, so the feedback covers the answers you gave.",
    "failed": "We couldn't generate feedback for this session.",
}


def mine(user):
    """The user's mock sessions that have not been deleted, with how many questions were answered."""
    return (
        InterviewSession.objects.filter(kind="mock", candidate_user=user, mock__deleted_at__isnull=True)
        .select_related("mock__target_role")
        .annotate(answered=Count("turns", filter=Q(turns__answered_at__isnull=False)))
    )


def feedback_status(session):
    """none, generating, ready, partial or failed, derived from the interview's own evaluation state (one source of truth)."""
    if session.status == SessionStatus.EVALUATING:
        return "generating"
    if session.status == SessionStatus.EVALUATION_FAILED:
        return "failed"
    if session.status == SessionStatus.EVALUATED:
        return "partial" if session.answered < session.question_target else "ready"
    return "none"


def _score(session):
    return float(session.overall_score) if session.overall_score is not None else None


def row(session):
    status = feedback_status(session)
    return {
        "id": session.pk, "date": session.invited_at, "role_title": session.role_title, "interview_type": session.mock.interview_type,
        "overall_score": _score(session), "status": session.status, "feedback_status": status,
        "answered_count": session.answered, "question_count": session.question_target,
    }  # fmt: skip


def detail(session):
    """The session, its current question while it is open, and the full report with the transcript once it is done."""
    status = feedback_status(session)
    role = session.mock.target_role
    data = {
        **row(session), "use_cv": session.mock.use_cv, "target_role": {"id": role.pk, "title": role.title} if role else None,
        "started_at": session.started_at, "completed_at": session.completed_at, "feedback_message": MESSAGES[status],
        "voice_available": settings.INTERVIEW_VOICE_ENABLED, "disclaimer": DISCLAIMER,
        "current_turn": None, "report": None, "transcript": [],
    }  # fmt: skip
    if session.status in OPEN_STATUSES:
        data["current_turn"] = engine.turn_payload(engine.current_turn(session))
    if session.status in FINISHED_STATUSES:
        data["report"] = session.report or None
        data["transcript"] = [
            {
                "index": t.index, "question": t.question_text, "answer": t.answer_text, "answer_source": t.answer_source,
                "score": float(t.score) if t.score is not None else None, "feedback": t.evaluation.get("feedback", ""),
                "criteria": t.evaluation.get("criteria", {}),
            }
            for t in session.turns.filter(answered_at__isnull=False).order_by("index")
        ]  # fmt: skip
    return data


def recent_for_dashboard(user):
    """The last 3 mock sessions for the candidate dashboard (Module 10)."""
    return [
        {"id": str(s.pk), "date": s.invited_at, "role_title": s.role_title, "status": s.status, "overall_score": _score(s)}
        for s in mine(user).order_by("-invited_at", "-id")[:3]
    ]
